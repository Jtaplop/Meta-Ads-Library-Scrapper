"""
results.py — Result files scanner, CSV/JSON reader, path validator, row count cache, and merger.
"""

from __future__ import annotations

import csv
import json
import re
from datetime import datetime
from pathlib import Path
from typing import Any, Literal

from loguru import logger

from api import settings
from api.schemas import AdRecord, MergeResponse, ResultDetailResponse, ResultFile

# Filename regex from SPEC-API §3.3
# e.g., "psicologia_ig_profiles_20261109_191111.csv" or "nike_20261109_191111.json"
FILENAME_REGEX = re.compile(
    r"^(?P<label>.+?)(?P<ig>_ig_profiles)?_(?P<ts>\d{8}_\d{6})\.(?P<fmt>csv|json)$",
    re.IGNORECASE,
)


class ResultsService:
    """
    Manages reading, listing, validating, deleting, and merging output files
    generated by the CLI scraper inside settings.OUTPUT_DIR.
    """

    def __init__(self, output_dir: Path | None = None) -> None:
        self._custom_output_dir: Path | None = output_dir.resolve() if output_dir else None
        self._row_cache: dict[tuple[str, int, int], int] = {}

    @property
    def output_dir(self) -> Path:
        return self._custom_output_dir or settings.OUTPUT_DIR.resolve()

    def validate_filename(self, filename: str) -> Path:
        """
        Validates that filename is safe against path traversal attacks and resolves
        strictly inside self.output_dir with a supported extension (.csv or .json).
        Raises ValueError if invalid.
        """
        if not filename or not isinstance(filename, str):
            raise ValueError("Filename must be a non-empty string")

        # Disallow slashes, backslashes, and directory traversal sequences
        if "/" in filename or "\\" in filename or ".." in filename:
            raise ValueError(f"Path traversal detected in filename: '{filename}'")

        # Must have valid extension
        lower_name = filename.lower()
        if not (lower_name.endswith(".csv") or lower_name.endswith(".json")):
            raise ValueError(f"Unsupported file format: '{filename}' (only .csv and .json allowed)")

        # Verify strict containment inside output directory
        target_path = (self.output_dir / filename).resolve()
        if target_path.parent != self.output_dir:
            raise ValueError(f"File '{filename}' resolves outside output directory")

        return target_path

    def _parse_filename_metadata(self, file_path: Path) -> tuple[str, bool, str, datetime]:
        """
        Parses label, ig_profiles_only flag, format, and created_at datetime
        from filename or fallback file stats.
        """
        filename = file_path.name
        match = FILENAME_REGEX.match(filename)
        stat = file_path.stat()

        if match:
            label = match.group("label")
            ig_profiles_only = bool(match.group("ig"))
            fmt = match.group("fmt").lower()
            ts_str = match.group("ts")
            try:
                created_at = datetime.strptime(ts_str, "%Y%m%d_%H%M%S")
            except ValueError:
                created_at = datetime.fromtimestamp(stat.st_mtime)
        else:
            stem = file_path.stem
            label = stem
            ig_profiles_only = "_ig_profiles" in stem
            fmt = file_path.suffix.lstrip(".").lower()
            created_at = datetime.fromtimestamp(stat.st_mtime)

        return label, ig_profiles_only, fmt, created_at

    def count_rows(self, file_path: Path) -> int:
        """
        Counts ad records in the file using caching based on (resolved_path, mtime_ns, size_bytes).
        """
        try:
            stat = file_path.stat()
        except OSError:
            return 0

        cache_key = (str(file_path.resolve()), stat.st_mtime_ns, stat.st_size)
        if cache_key in self._row_cache:
            return self._row_cache[cache_key]

        count = 0
        try:
            suffix = file_path.suffix.lower()
            if suffix == ".csv":
                with open(file_path, "r", encoding="utf-8-sig", errors="replace") as f:
                    reader = csv.reader(f)
                    total_lines = sum(1 for line in reader if line)
                    count = max(0, total_lines - 1)  # subtract header row
            elif suffix == ".json":
                with open(file_path, "r", encoding="utf-8", errors="replace") as f:
                    data = json.load(f)
                    if isinstance(data, list):
                        count = len(data)
                    elif isinstance(data, dict):
                        count = 1
        except Exception as exc:
            logger.debug(f"Failed to count rows in {file_path.name}: {exc}")
            count = 0

        self._row_cache[cache_key] = count
        return count

    def list_results(
        self,
        q: str | None = None,
        fmt: str | None = None,
        ig_only: bool | None = None,
        job_file_map: dict[str, str] | None = None,
    ) -> list[ResultFile]:
        """
        Scans settings.OUTPUT_DIR for .csv and .json files, applies filters,
        and returns list[ResultFile] sorted by created_at descending.
        """
        if not self.output_dir.exists() or not self.output_dir.is_dir():
            return []

        results: list[ResultFile] = []
        clean_q = q.strip().lower() if q else None
        clean_fmt = fmt.strip().lower() if fmt else None
        job_map = job_file_map or {}

        try:
            for entry in self.output_dir.iterdir():
                if not entry.is_file():
                    continue

                suffix = entry.suffix.lower()
                if suffix not in (".csv", ".json"):
                    continue

                label, ig_profiles_only, file_fmt, created_at = self._parse_filename_metadata(entry)

                # Filter by format
                if clean_fmt and file_fmt != clean_fmt:
                    continue

                # Filter by ig_only
                if ig_only is not None and ig_profiles_only != ig_only:
                    continue

                # Filter by query search
                if clean_q:
                    if clean_q not in entry.name.lower() and clean_q not in label.lower():
                        continue

                stat = entry.stat()
                rows = self.count_rows(entry)
                job_id = job_map.get(entry.name)

                results.append(
                    ResultFile(
                        filename=entry.name,
                        label=label,
                        ig_profiles_only=ig_profiles_only,
                        format=file_fmt,  # type: ignore[arg-type]
                        created_at=created_at,
                        size_bytes=stat.st_size,
                        rows=rows,
                        job_id=job_id,
                    )
                )
        except Exception as exc:
            logger.error(f"Error scanning output dir {self.output_dir}: {exc}")

        # Sort by created_at descending
        results.sort(key=lambda rf: rf.created_at, reverse=True)
        return results

    def get_result(self, filename: str) -> ResultDetailResponse:
        """
        Reads CSV (via csv.DictReader with utf-8-sig) or JSON (via json.load with utf-8)
        and normalizes records into list[AdRecord].
        """
        path = self.validate_filename(filename)
        if not path.is_file():
            raise FileNotFoundError(f"Result file '{filename}' not found")

        label, ig_profiles_only, file_fmt, created_at = self._parse_filename_metadata(path)
        stat = path.stat()

        records: list[AdRecord] = []
        suffix = path.suffix.lower()

        if suffix == ".csv":
            with open(path, "r", encoding="utf-8-sig", newline="", errors="replace") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    # Clean up empty strings or whitespace
                    norm_row: dict[str, Any] = {}
                    for k, v in row.items():
                        if k is None:
                            continue
                        clean_k = k.strip()
                        norm_row[clean_k] = v.strip() if isinstance(v, str) else v

                    # Ensure ad_id and page_id are strings
                    if "ad_id" in norm_row and norm_row["ad_id"] is not None:
                        norm_row["ad_id"] = str(norm_row["ad_id"])
                    if "page_id" in norm_row and norm_row["page_id"] is not None:
                        norm_row["page_id"] = str(norm_row["page_id"])

                    try:
                        record = AdRecord.model_validate(norm_row)
                        records.append(record)
                    except Exception as exc:
                        logger.debug(f"Failed to validate CSV row in {filename}: {exc}")

        elif suffix == ".json":
            with open(path, "r", encoding="utf-8", errors="replace") as f:
                raw_data = json.load(f)
                items = raw_data if isinstance(raw_data, list) else [raw_data]

                for item in items:
                    if not isinstance(item, dict):
                        continue
                    norm_item = dict(item)
                    if "ad_id" in norm_item and norm_item["ad_id"] is not None:
                        norm_item["ad_id"] = str(norm_item["ad_id"])
                    if "page_id" in norm_item and norm_item["page_id"] is not None:
                        norm_item["page_id"] = str(norm_item["page_id"])

                    try:
                        record = AdRecord.model_validate(norm_item)
                        records.append(record)
                    except Exception as exc:
                        logger.debug(f"Failed to validate JSON item in {filename}: {exc}")

        file_info = ResultFile(
            filename=path.name,
            label=label,
            ig_profiles_only=ig_profiles_only,
            format=file_fmt,  # type: ignore[arg-type]
            created_at=created_at,
            size_bytes=stat.st_size,
            rows=len(records),
        )

        return ResultDetailResponse(file=file_info, rows=records)

    def delete_result(self, filename: str) -> None:
        """
        Deletes the specified file inside OUTPUT_DIR after validating safety.
        """
        path = self.validate_filename(filename)
        if not path.is_file():
            raise FileNotFoundError(f"Result file '{filename}' not found")

        path.unlink()

        # Remove from row cache
        to_del = [k for k in self._row_cache if k[0] == str(path.resolve())]
        for k in to_del:
            self._row_cache.pop(k, None)

    def merge_results(
        self,
        filenames: list[str],
        dedupe_by: Literal["ad_id", "ig_username", "page_id"] = "ad_id",
    ) -> MergeResponse:
        """
        Reads all specified result files, merges their rows, deduplicates by the chosen field,
        preserving the earliest start_date (or first seen if no start_date), and returns MergeResponse.
        """
        all_records: list[AdRecord] = []
        for fname in filenames:
            detail = self.get_result(fname)
            all_records.extend(detail.rows)

        total_before = len(all_records)
        seen_indices: dict[str, int] = {}
        output_records: list[AdRecord] = []

        for rec in all_records:
            key_val = getattr(rec, dedupe_by, None)
            if key_val is None or key_val == "":
                # Unkeyed record: cannot deduplicate against other records, preserve
                output_records.append(rec)
                continue

            key_str = str(key_val).strip()
            if key_str not in seen_indices:
                seen_indices[key_str] = len(output_records)
                output_records.append(rec)
            else:
                idx = seen_indices[key_str]
                existing = output_records[idx]

                # Compare start_date to preserve earliest date
                replace = False
                if existing.start_date is None and rec.start_date is not None:
                    replace = True
                elif existing.start_date is not None and rec.start_date is not None:
                    if rec.start_date < existing.start_date:
                        replace = True

                if replace:
                    output_records[idx] = rec

        return MergeResponse(
            rows=output_records,
            total_before_dedupe=total_before,
            total_after_dedupe=len(output_records),
        )


# Default singleton instance for the application
results_service = ResultsService()
